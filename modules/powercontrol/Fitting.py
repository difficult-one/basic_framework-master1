# Extract features. Loss terms use abs(); the I*W term keeps direction.
I_signed = np.array([x[0] for x in data])
W_signed = np.array([x[1] for x in data])
I = np.abs(I_signed)
W = np.abs(W_signed)
y = np.array([x[2] for x in data])

# Design matrix X: [1, abs(I), abs(W), signed I*W, I^2, W^2]
X = np.column_stack([np.ones_like(I), I, W, I_signed * W_signed, I**2, W**2])

# 最小二乘求解
coeffs, residuals, _, _ = np.linalg.lstsq(X, y, rcond=None)

# 输出系数
print("Fitted coefficients:")
print(f"K0 = {coeffs[0]:.6f}")
print(f"K1 = {coeffs[1]:.6f}")
print(f"K2 = {coeffs[2]:.6f}")
print(f"K3 = {coeffs[3]:.6f}")
print(f"K4 = {coeffs[4]:.6f}")
print(f"K5 = {coeffs[5]:.6f}\n")

# 计算预测值和残差
y_pred = X @ coeffs
residuals = y - y_pred

# 模型拟合评价指标
ss_total = np.sum((y - np.mean(y))** 2)
ss_residual = np.sum(residuals ** 2)
r_squared = 1 - (ss_residual / ss_total)
mse = np.mean(residuals** 2)

print("Fit quality:")
print(f"R^2: {r_squared:.6f}")
print(f"MSE: {mse:.6f}")
print(f"Residual sum of squares: {ss_residual:.6f}\n")

# 检测异常值
